# ── Asset helpers ──────────────────────────────────────────────────────────────

def _default_logo_path():
    for name in ("logo_transparent.png", "logo.png"):
        p = os.path.join(ASSETS_DIR, name)
        if os.path.exists(p):
            return p
    return None


def _watermark_path():
    p = os.path.join(ASSETS_DIR, "logo_watermark.png")
    return p if os.path.exists(p) else None


def _get_blurred_watermark() -> str | None:
    """Blur + soften the watermark PNG using Pillow and cache it."""
    wm = _watermark_path()
    if not wm:
        return None
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    try:
        from PIL import Image as PILImage, ImageFilter
        img = PILImage.open(wm).convert("RGBA")
        r, g, b, a = img.split()
        # 18% opacity — subtle background, not distracting
        a = a.point(lambda px: int(px * 0.30))
        img.putalpha(a)
        img = img.filter(ImageFilter.GaussianBlur(radius=3))
        img.save(_WM_BLURRED, "PNG")
        return _WM_BLURRED
    except Exception as e:
        print(f"[PDF] Watermark blur error: {e}")
        return wm   # fallback to original


def _get_qr_png() -> str | None:
    """Return the pre-generated WhatsApp QR code PNG, or try to generate it."""
    # Use cached file if it already exists (generated by setup or previous run)
    if os.path.exists(_QR_WA_PNG):
        return _QR_WA_PNG
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    try:
        import qrcode as _qrcode
        qr = _qrcode.QRCode(
            version=1,
            error_correction=_qrcode.constants.ERROR_CORRECT_M,
            box_size=8, border=2,
        )
        qr.add_data(WA_QR_URL)
        qr.make(fit=True)
        img = qr.make_image(fill_color="#1E3A6E", back_color="white")
        img.save(_QR_WA_PNG)
        return _QR_WA_PNG
    except Exception as e:
        print(f"[PDF] QR code error: {e}")
        return None


def _parse_date(value) -> datetime:
    if not value:
        return datetime.now()
    try:
        return datetime.fromtimestamp(int(value))
    except (ValueError, TypeError):
        pass
    try:
        return datetime.strptime(str(value), "%Y-%m-%d")
    except (ValueError, TypeError):
        pass
    return datetime.now()


